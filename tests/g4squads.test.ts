import './jsdomEnv';
import assert from 'node:assert/strict';
import { Input } from '../src/core/input';
import { StaticBoxGrid } from '../src/core/spatialHash';
import { ENEMIES, patrolDefs } from '../src/data/enemies';
import { Game } from '../src/game/game';
import { PickupType } from '../src/game/pickups';
import { ordersFor, patrolTuning, PatrolOrders } from '../src/game/squads';
import { holdPatrolRefill, patrolRing, spawnPatrol } from '../src/game/systems/spawning';
import { preparePatrols, onEnemyKilled } from '../src/game/systems/enemyAi';
import { packEnemies, unpackEnemies } from '../src/net/codec';
import { CODEX } from '../src/data/codex';
import { localize, setLanguage } from '../src/i18n';

const g = new Game(new Input(document.querySelector('canvas')!), 16 / 9, document.querySelector('#hud')!, document.querySelector('#reticle')!);
g.startSolo(); g.closeShop(); g.enemies.clear();
g.walls = new StaticBoxGrid([]);
g.arena.hazards.length = 0;
Object.assign(g.hero.player.pos, { x: 0, z: 0 });
const mate = g.makeHero(1, 'Mate', [], 'remote');
Object.assign(mate.player.pos, { x: 16, z: 0 });
g.setHeroes([g.hero, mate]);
g.role = 'host'; g.stage = 3; g.director.ringsSent = 2;
g.role = 'client';
assert.equal(patrolRing(g, 50), 0);
assert.equal(spawnPatrol(g, 0, -9, 0, 1, 5), 0);
g.role = 'host';
assert.equal(spawnPatrol(g, 0, -9, 0, 1, 4), 0);
assert.equal(spawnPatrol(g, 0, -2, 0, 1, 5), 0, 'no spawn on a teammate');
assert.equal(spawnPatrol(g, g.arena.halfSize, 0, 0, 1, 5), 0, 'no partial formation');
assert.equal(spawnPatrol(g, 0, -9, 0, 1, 5), 5);
const brain = ordersFor(g);
const actors = g.enemies.list.filter(e => e.active);
const c = actors.find(e => e.def === patrolDefs.commander)!;
const s = actors.find(e => e.def === patrolDefs.marksman)!;
const bait = actors.find(e => e.def === patrolDefs.baiter)!;
const wall = actors.filter(e => e.def === patrolDefs.bulwark);
for (const e of actors) { e.state = 'move'; e.frozen = 0; }
const tick = () => {
  const old = preparePatrols(g, 1 / 60);
  g.enemies.update(1 / 60, g.enemyCtx);
  g.enemyCtx.lure = old;
};
const advance = (frames: number) => { for (let i = 0; i < frames; i++) tick(); };
g.enemyCtx.targets = [g.hero, mate].map(h => ({ x: h.player.x, z: h.player.z, alive: true, radius: h.player.radius }));
for (const guard of wall) guard.z -= 2;
s.x = 12; s.z = -2; s.timerA = 0;
c.rallyCd = 0;
g.vfx.recording = true;
tick();
assert.equal(brain.members.get(c)!.focus, g.hero);
assert.ok(wall.every(e => e.rallyT > 2));
assert.equal(s.rallyT, 0, 'only nearby allies receive the buff');
assert.equal(s.state, 'windup');
assert.ok(s.lungeX < 0, 'sniper aims at shared focus even with a closer teammate to its right');
assert.ok(g.vfx.events.some(f => f[0] === 'a' && f[3] === 'threatSniper'));
const left = brain.members.get(wall[0])!, right = brain.members.get(wall[1])!;
assert.ok(Math.abs(left.x - right.x) > 2 && Math.abs(left.z - right.z) < 1e-6);
Object.assign(g.hero.player.pos, { x: 0, z: -6 }); advance(6);
assert.ok(brain.members.get(c)!.z < c.z, 'the crown backs away when rushed');
s.t = 0.2;
const lockedX = s.lungeX, lockedZ = s.lungeZ;
Object.assign(g.hero.player.pos, { x: 2, z: 0 }); advance(14);
assert.equal(g.bullets.count, 1);
assert.ok(g.bullets.life[0] * Math.hypot(g.bullets.vx[0], g.bullets.vz[0]) + s.radius + 0.2 <= 20.001, 'the shot stops at the end of its visible line');
assert.ok(Math.abs(g.bullets.vx[0] / Math.hypot(g.bullets.vx[0], g.bullets.vz[0]) - lockedX) < 1e-5);
assert.equal(s.lungeZ, lockedZ);
const front = wall[0];
front.facing = 0;
assert.equal(g.damage(front, 20, { source: 'buster', dirX: 0, dirZ: -1 }, g.hero), 1);
assert.ok(g.damage(front, 20, { source: 'buster', dirX: 0, dirZ: 1 }, g.hero) > 1);
g.damage(front, 2, { source: 'charge', dirX: 0, dirZ: -1 }, g.hero);
assert.equal(front.familyState, 1);
assert.ok(g.damage(front, 20, { source: 'buster', dirX: 0, dirZ: -1 }, g.hero) > 1);

g.arena.hazards.push({ kind: 'quicksand', x: 5, z: -3, r: 2 });
bait.x = 3; bait.z = -3; bait.timerB = 0; advance(6);
assert.ok(brain.members.get(bait)!.x > 5, 'bait crosses the far lip of the hazard');
const trap = g.strikes.at(-1)!;
assert.equal(trap.t, patrolTuning.trapTell);
assert.ok(g.vfx.events.some(f => f[0] === 'z' && f[1] === trap.x && f[2] === trap.z && f[3] === trap.r));

Object.assign(mate.player.pos, { x: 0, z: -12 });
const oldFocus = brain.members.get(c)!.focus;
brain.due = patrolTuning.tick;
tick();
assert.equal(brain.members.get(c)!.focus, oldFocus, 'no focus rescan between ticks');
advance(6); assert.equal(brain.members.get(c)!.focus, mate);
mate.left = true; advance(6); assert.equal(brain.members.get(c)!.focus, g.hero);
s.state = 'windup'; s.t = 0.001;
const drops = g.pickups.count;
g.hero.player.hp = g.hero.player.maxHp * 0.75;
onEnemyKilled.call(g, c, g.hero); g.enemies.kill(c);
assert.equal(g.pickups.count, drops + 2);
assert.equal(g.pickups.type[drops], PickupType.Chest);
assert.equal(g.pickups.type[drops + 1], PickupType.Heart);
const innocent = g.enemies.spawn(ENEMIES.bopper, 20, 20, { instant: true });
assert.equal(innocent, c, 'exercise pooled commander reuse');
advance(190);
assert.ok(actors.filter(e => e !== c).every(e => !e.active));
assert.ok(innocent.active); assert.equal(g.bullets.count, 1, 'no last shot after losing the leader');

// A promoted host has actor definitions, positions and HP but no JS object links.
// Rebuild two independent squads and assign distinct sides to both shield pairs.
g.enemies.clear();
for (const x of [-11, 11]) for (const role of ['commander', 'bulwark', 'bulwark', 'marksman'] as const)
  g.enemies.spawn(patrolDefs[role], x, -6, { instant: true });
const promoted = new PatrolOrders();
promoted.reconcile(g, 8);
for (const o of promoted.members.values()) {
  if (o.unit.def.patrolRole === 'commander') continue;
  assert.equal(o.captain!.unit.x, o.unit.x);
}
const rank = [...promoted.members.values()].filter(o => o.unit.def.patrolRole === 'bulwark' && o.unit.x < 0);
assert.notEqual(rank[0].side, rank[1].side);
g.enemies.clear(); g.director.ringsSent = 3; g.seed = 3;
g.stage = 2; assert.equal(patrolRing(g, 1), 0);
g.stage = 3; g.director.adaptive.power.ready = true; g.director.adaptive.power.score = 0.6;
assert.equal(patrolRing(g, 1), 0, 'a team under pressure gets its ordinary ring');
g.director.adaptive.power.score = 0.7;
assert.equal(patrolRing(g, 1), 0, 'hunters require a stronger team than a patrol');
g.director.adaptive.power.score = 0.9; const hp = g.hero.player.hp; g.hero.player.hp = 1;
assert.equal(patrolRing(g, 1), 0); g.hero.player.hp = hp;
assert.equal(patrolRing(g, 1), 1); assert.equal(patrolRing(g, 1), 0);
const hunter = g.enemies.list.find(e => e.active)!; hunter.state = 'move';
hunter.x = 0; hunter.z = -3;
g.vfx.events.length = 0;
advance(6 * 100);
assert.equal(hunter.familyState, 1); assert.equal(hunter.state, 'move');
assert.equal(hunter.contactDamage, 0);
assert.ok(g.vfx.events.filter(f => f[0] === 'a' && f[3] === 'ghostWail').length >= 3);
unpackEnemies(packEnemies([hunter]), r => { assert.equal(r.def, patrolDefs.hunter); assert.equal(r.familyState, 1); });
const remaining = hunter.timerB;
g.role = 'client'; preparePatrols(g, 2); assert.equal(hunter.timerB, remaining);
g.role = 'host'; advance(6 * 23); assert.equal(hunter.familyState, 2);
hunter.x = g.hero.player.x; hunter.z = g.hero.player.z - 3; hunter.timerA = 0;
advance(1); assert.equal(hunter.state, 'windup'); assert.ok(hunter.t >= 1);
unpackEnemies(packEnemies([hunter]), r => {
  assert.equal(r.state, 'windup'); assert.ok(Math.abs(r.targetX - hunter.targetX) < 0.02);
});
g.enemies.clear(); g.director.ringsSent = 2;
g.director.adaptive.power.score = 0.7;
g.ringPoint = () => ({ x: 0, z: -14 });
g.stage = 1; assert.equal(patrolRing(g, 30), 0);
g.stage = 2;
assert.equal(patrolRing(g, 30), 30, 'the formation takes the entire scheduled ring');
assert.equal(g.enemies.activeCount, 5, 'the two flanks remain open');
const refill = { kind: 'enemy', def: ENEMIES.swarmer } as const;
assert.ok(holdPatrolRefill(g, refill));
assert.ok(holdPatrolRefill(g, { ...refill, def: ENEMIES.v_bopper }));
assert.equal(holdPatrolRefill(g, { ...refill, elite: true }), false);
assert.equal(holdPatrolRefill(g, { kind: 'enemy', def: ENEMIES.golden }), false);
g.director.time += patrolTuning.entryTime;
assert.equal(holdPatrolRefill(g, refill), false, 'the next ordinary body is due after the four-second entrance');
assert.equal(patrolRing(g, 30), 0, 'only one commander can occupy the ring');
g.enemies.clear();
g.hero.player.hp = g.hero.player.maxHp * 0.4;
assert.equal(patrolRing(g, 30), 30, 'a wounded party can break the crown behind two plates');
assert.equal(g.enemies.activeCount, 3);
assert.ok(g.enemies.list.every(e => !e.active || e.contactDamage === 0 && !e.def.leap && !e.def.shoot && e.def.patrolRole !== 'baiter'));
g.director.time += patrolTuning.entryTime;
assert.ok(holdPatrolRefill(g, refill));
g.director.time += patrolTuning.reliefTime - patrolTuning.entryTime;
assert.equal(holdPatrolRefill(g, refill), false);
g.enemies.clear();
g.stage = 1; g.director.ringsSent = 5;
g.hero.player.hp = g.hero.player.maxHp;
assert.equal(patrolRing(g, 30), 0, 'a healthy first-stage party keeps its normal wave');
g.hero.player.hp *= 0.8;
assert.equal(patrolRing(g, 30), 30, 'the first recovery formation arrives while a heart is still useful');
assert.equal(g.enemies.activeCount, 3);
g.enemies.clear();
g.stage = 3; g.director.ringsSent = 1; g.director.adaptive.power.ready = false;
assert.equal(patrolRing(g, 30), 30, 'later stages open with shields before the power window fills');
assert.equal(g.enemies.activeCount, 3);
g.enemies.clear();
g.stage = 2; g.director.adaptive.power.ready = true;
g.director.ringsSent = 5;
assert.equal(patrolRing(g, 500), 500, 'a capped ring also leaves both flanks open');
assert.equal(g.enemies.activeCount, 5);
const ranged = g.enemies.list.find(e => e.active && e.def.patrolRole === 'marksman')!;
const shot = g.bullets.count;
g.enemyCtx.fireBullet(ranged, 0, 1, 40, 15);
assert.ok(Math.abs(g.bullets.life[shot] * g.bullets.vz[shot] + ranged.radius + 0.2 - 20) < 0.001, 'double-speed shots have the same painted reach');
const plate = g.enemies.list.find(e => e.active && e.def.patrolRole === 'bulwark')!;
plate.state = 'move'; plate.timerB = 0;
const gap = g.enemies.spawn(ENEMIES.bopper, plate.x + 1, plate.z - 2, { instant: true });
g.hash.clear(); g.hash.insert(gap, gap.x, gap.z, gap.radius); tick();
assert.equal(gap.guardT, 0, 'a soldier standing behind an open lane has no invisible shield');
g.curses.push('c_famine');
const crown = g.enemies.list.find(e => e.active && e.def.patrolRole === 'commander')!;
const priorDrops = g.pickups.count;
g.role = 'client';
onEnemyKilled.call(g, crown, g.hero);
assert.equal(g.pickups.count, priorDrops, 'only the host pays the crown');
g.role = 'host';
onEnemyKilled.call(g, crown, g.hero);
assert.equal(g.pickups.count, priorDrops + 1);
assert.equal(g.pickups.type[priorDrops], PickupType.Chest, 'Famine allows the shared chest and suppresses the recovery heart');
for (const lang of ['en', 'ar'] as const) {
  await setLanguage(lang);
  for (const def of Object.values(patrolDefs)) {
    const entry = CODEX.find(card => card.id === 'enemy:' + def.id)!;
    const text = localize(entry.text);
    assert.ok(text.length > 50);
    if (lang === 'ar') assert.doesNotMatch(text, /[a-z]{3}/i);
  }
}
console.log('Patrol tactics, warnings, pool reuse, restored squads, localization and snapshot cues passed.');
