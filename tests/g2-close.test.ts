import { seedRandom } from './jsdomEnv';
import assert from 'node:assert/strict';
import type { NetClient } from '../src/net/peer';

const { Game } = await import('../src/game/game');
const { Input } = await import('../src/core/input');
const { ENEMIES } = await import('../src/data/enemies');
const { bossMoveTuning } = await import('../src/game/bosses');
const { buildMig, restoreRun, hostmigState, hostmigTick } = await import('../src/game/systems/hostmig');
const { netcodeState } = await import('../src/game/systems/netcode');
const { AdaptivePace, adaptiveTuning } = await import('../src/game/director');
const pace = new AdaptivePace();
pace.assist = false;
pace.power.ready = true;
pace.power.score = adaptiveTuning.powerStart;
for (let i = 0; i < 60; i++) pace.step(1, 1, 4, 1, 4);
assert.equal(pace.pressure, 1, 'crossing the score threshold alone cannot add a full cruising crowd');
pace.power.score = 1;
for (let i = 0; i < 60; i++) pace.step(1, 1, 4, 1, 4, 0);
assert.equal(pace.pressure, 1, 'a full field has no room for extra bodies even at high power');
for (let i = 0; i < 60; i++) pace.step(1, 1, 4, 1, 4);
assert.equal(pace.pressure, adaptiveTuning.max);
seedRandom(42);
const input = new Input(document.querySelector<HTMLCanvasElement>('#game')!);
const g = new Game(input, 16 / 9, document.getElementById('hud')!, document.getElementById('reticle')!);
g.startRun({ seed: 42, difficulty: 'normal' });
if (g.mode === 'shop') g.closeShop();
const king = g.enemies.spawn(ENEMIES.king, 0, 0, { instant: true });
const waves = g.bossField.waves;
const land = (remaining: number) => {
  king.burst = remaining;
  g.bossApi.shockwave(king, 0, 0, 0);
  g.bossApi.shockwave(king, 0, 0, 0.45);
};
land(3);
land(2);
assert.equal(waves.length, 0);
g.vfx.recording = true;
land(1);
assert.equal(waves.length, 1);
assert.equal(waves[0].delay, bossMoveTuning.firstKingShockTell);
assert.ok(g.vfx.drain().some(e => e[0] === 'r' && e[4] < 1), 'protected shrinking warning reaches the effects bus');
const start = waves[0].r;
const p = g.player;
p.teleport(start + 0.6, 0);
p.aim.x = -1;
p.aim.z = 0;
p.invuln = 0;
const hp = p.hp;
const stock = p.dashStock;
while (waves[0].delay > 0) g.updateBossFight(1 / 60);
assert.equal(p.hp, hp);
assert.equal(waves[0].r, start);
for (let i = 0; i < 35; i++) {
  p.update(1 / 60, null, [], i === 0);
  g.updateBossFight(1 / 60);
}
assert.equal(p.dashStock, stock - 1, 'crossing the opening wave spends one stamina pip');
assert.equal(p.hp, hp, 'one starter dash crosses the opening wave');
waves.length = 0;
p.teleport(start + 0.6, 0);
p.invuln = 0;
land(1);
for (let i = 0; i < 60; i++) g.updateBossFight(1 / 60);
assert.ok(p.hp < hp, 'the same wave hits a stationary hero after the warning');
waves.length = 0;
g.stage = 5;
land(3);
assert.deepEqual(waves.map(w => w.delay), [0, 0.45], 'the returning King retains paired waves');

g.stage = 1;
g.openShop();
const offer = g.hero.shopOffers[0]!;
const cost = g.hero.price(offer);
g.hero.gold = cost;
assert.equal(g.hero.buy(0), '');
g.hero.gold = 12;
p.hp = 10;
const before = buildMig(g);
assert.equal(g.hero.heal(), '');
const paid = buildMig(g);
const offers = g.hero.shopOffers.map(m => m?.id);
// The checkpoint for the purchase arrived ahead of the next display snapshot.
g.hero.gold = before.heroes[0].gold;
p.hp = before.heroes[0].hp;
restoreRun(g, paid);
assert.equal(g.mode, 'shop');
assert.equal(g.hero.gold, 9);
assert.equal(p.hp, paid.heroes[0].hp);
assert.ok(g.hero.shopHealed);
assert.deepEqual(g.hero.shopOffers.map(m => m?.id), offers);
const slot = g.hero.synergy.slots.find(s => s.def.id === offer.id)!;
assert.equal(slot.paid, cost, 'the purchase retains its sell value after promotion');
assert.equal(g.hero.heal(), 'ALREADY HEALED');
assert.equal(g.hero.gold, 9);
delete paid.heroes[0].build.mods[0].paid;
restoreRun(g, paid);
assert.equal(g.hero.synergy.slots[0].paid, 0, 'older builds without a receipt still restore');

// A slow reconnect to a live host can outlast the election's probe window.
g.role = 'client';
const migration = hostmigState(g);
migration.mig = paid;
migration.phase = 'probe';
migration.until = 0;
const rc = netcodeState(g);
rc.rc = { code: 'ABCDE', name: 'Guest', until: Infinity, next: 0, tries: 1,
  pending: {} as NetClient, hello: false, helloAt: 0 };
hostmigTick(g);
assert.equal(migration.phase, 'probe');
assert.equal(g.role, 'client');
rc.rc.pending = null;
rc.rc.hello = true;
hostmigTick(g);
assert.equal(migration.phase, 'blip');
assert.equal(g.role, 'client');
