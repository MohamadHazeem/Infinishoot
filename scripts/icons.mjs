const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/game-icons/icons.json', import.meta.url), 'utf8'));
const out = {};
for (const [id, name] of Object.entries(ART)) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`game-icons has no icon named "${name}" (for ${id})`);
  const paths = [...icon.body.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`"${name}" has no paths`);
  out[id] = { name, paths };
}
const size = set.width ?? 512;
const lines = Object.entries(out).map(([id, { name, paths }]) => `  // ${name}\n  ${id}: ${JSON.stringify(paths)},`);
writeFileSync(
  new URL('../src/data/iconArt.ts', import.meta.url),
  `// Generated by scripts/icons.mjs. Do not edit by hand.
// Icons from game-icons.net by Lorc, Delapouite and contributors, CC BY 3.0
// (https://creativecommons.org/licenses/by/3.0/).

/** Source icon size (the paths' coordinate space). */
export const ICON_ART_SIZE = ${size};

/** Item id -> SVG path data. */
export const ICON_ART: Record<string, string[]> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote ${Object.keys(out).length} icons to src/data/iconArt.ts`);
