CREATE TABLE IF NOT EXISTS abyss_run (
  ticket TEXT PRIMARY KEY, week INTEGER NOT NULL, start INTEGER NOT NULL, pilot TEXT NOT NULL,
  floor INTEGER NOT NULL DEFAULT 1, reached INTEGER NOT NULL
) WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS abyss_run_week ON abyss_run(week);
CREATE TABLE IF NOT EXISTS abyss_first (
  week INTEGER NOT NULL, floor INTEGER NOT NULL, pilot TEXT NOT NULL, PRIMARY KEY (week, floor)
) WITHOUT ROWID;
